use crc32fast::Hasher;

/// Baichuan's UDP discovery packets use CRC-32 with the standard
/// CRC-32/ISO-HDLC polynomial but an effective init/xorout of 0, which is why
/// we seed the hasher with 0xffffffff and undo the library's xorout below.
pub fn calc_crc(payload: &[u8]) -> u32 {
    let mut hasher = Hasher::new_with_initial(0xffffffff);
    hasher.update(payload);
    hasher.finalize() ^ 0xffffffff
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn crc_of_empty_is_zero() {
        assert_eq!(calc_crc(&[]), 0);
    }

    #[test]
    fn crc_is_deterministic_and_sensitive_to_content() {
        let a = calc_crc(b"hello world");
        let b = calc_crc(b"hello world");
        let c = calc_crc(b"hello worlD");
        assert_eq!(a, b);
        assert_ne!(a, c);
    }

    #[test]
    fn crc_matches_a_real_captured_relay_reply() {
        // Ground truth from a live packet capture against the real Reolink
        // P2P relay infrastructure during MVP debugging (2026-09-13): the
        // 104-byte encrypted payload of a genuine M2C_Q_R reply, and the
        // checksum the relay itself put in that same packet's header.
        let encrypted: [u8; 104] = [
            0xe1, 0xce, 0x64, 0x6c, 0x21, 0xde, 0xd8, 0x45, 0x9e, 0xcf, 0x11, 0x0a, 0xbe, 0xfb,
            0xa6, 0xeb, 0xd4, 0x11, 0x0d, 0xd1, 0x45, 0x64, 0xcc, 0xb0, 0x23, 0x30, 0xe9, 0xd9,
            0x09, 0x0a, 0x71, 0x47, 0xbe, 0xa0, 0x66, 0x00, 0x30, 0x8f, 0xe7, 0x14, 0xe3, 0xac,
            0x6f, 0x27, 0x89, 0xb1, 0xe8, 0xe6, 0x83, 0x40, 0x0c, 0xc6, 0x08, 0x2f, 0x97, 0xfc,
            0x76, 0x78, 0xb4, 0xc4, 0x52, 0x54, 0x69, 0x52, 0xe3, 0xa2, 0x37, 0x5f, 0x21, 0xd2,
            0xa9, 0x58, 0xbc, 0xf3, 0x7e, 0x69, 0x9e, 0xb6, 0xea, 0xa1, 0x90, 0x4f, 0x54, 0x8c,
            0x18, 0x29, 0x80, 0xfc, 0x7a, 0x6b, 0xd6, 0x92, 0x74, 0x69, 0x4d, 0x6a, 0x8f, 0xa0,
            0x6a, 0x13, 0x4f, 0xd0, 0xc5, 0x49,
        ];
        assert_eq!(calc_crc(&encrypted), 0x4277167f);
    }
}
